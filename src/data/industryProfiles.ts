export const industryTemplates: IndustryTemplate[] = industryProfiles.map(profile => ({
  id: `template-${profile.id}`,
  name: `${profile.name} Template`,
  industryType: profile.type,
  description: profile.description,
  features: profile.recommendedFeatures,
  scenarios: profile.defaultScenarios,
  dashboardConfig: profile.dashboardLayout,
  recommendedAddons: profile.integrations,
  estimatedSetupTime: profile.type === 'personal' ? 15 : profile.type === 'smart_city' ? 120 : 45,
  complexity: profile.type === 'personal' ? 'beginner' : profile.type === 'smart_city' || profile.type === 'manufacturing' ? 'advanced' : 'intermediate',
}))

export function getIndustryProfile(type: string): IndustryProfile | undefined {
  return industryProfiles.find(p => p.type === type || p.id === type)
}

export function getIndustryTemplate(type: string): IndustryTemplate | undefined {
  return industryTemplates.find(t => t.industryType === type || t.id === type)
}

